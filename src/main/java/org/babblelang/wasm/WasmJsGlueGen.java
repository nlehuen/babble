package org.babblelang.wasm;

/**
 * Generates the sibling ES module loader ({@code app.mjs}) for {@code -target wasm-js}
 * ({@code BIP025-P1}, {@code BIP025-P4}, {@code BIP025-D4}, {@code BIP025-D8}).
 *
 * <p>Works identically in Node.js (v22+) and modern browsers (Chrome/Edge/Firefox/Safari with
 * WasmGC + {@code wasm:js-string} builtins). Supplies {@code babble:env} imports with exact Java
 * {@code Double.toString}/{@code Float.toString} formatting and stdout/stderr sinks.
 */
public final class WasmJsGlueGen {
    private WasmJsGlueGen() {
    }

    /** Generates the ES module glue referencing the sibling {@code wasmFileName}. */
    public static String generate(String wasmFileName) {
        String escapedName = wasmFileName.replace("\\", "\\\\").replace("\"", "\\\"");
        return """
                // Generated by Babble WebAssembly compiler (babblec -target wasm-js)
                const WASM_FILE = "%s";

                function formatJavaMantissa(m) {
                  return m.includes(".") ? m : m + ".0";
                }

                export function formatJavaDouble(d) {
                  if (Number.isNaN(d)) return "NaN";
                  if (d === Infinity) return "Infinity";
                  if (d === -Infinity) return "-Infinity";
                  if (d === 0) return Object.is(d, -0) ? "-0.0" : "0.0";
                  const neg = d < 0;
                  const abs = neg ? -d : d;
                  const sign = neg ? "-" : "";
                  if (abs >= 1e-3 && abs < 1e7) {
                    const s = String(abs);
                    return sign + formatJavaMantissa(s);
                  }
                  const s = abs.toExponential();
                  const [mant, expPart] = s.split("e");
                  const exp = parseInt(expPart, 10);
                  return sign + formatJavaMantissa(mant) + "E" + exp;
                }

                export function formatJavaFloat(f) {
                  const v = Math.fround(f);
                  if (Number.isNaN(v)) return "NaN";
                  if (v === Infinity) return "Infinity";
                  if (v === -Infinity) return "-Infinity";
                  if (v === 0) return Object.is(v, -0) ? "-0.0" : "0.0";
                  const neg = v < 0;
                  const abs = neg ? -v : v;
                  const sign = neg ? "-" : "";
                  // Find shortest decimal precision (1..9 significant digits) that round-trips to v
                  let best = abs.toPrecision(9);
                  for (let p = 1; p <= 9; p++) {
                    const cand = abs.toPrecision(p);
                    if (Math.fround(Number(cand)) === abs) {
                      best = cand;
                      break;
                    }
                  }
                  const num = Number(best);
                  if (abs >= 1e-3 && abs < 1e7) {
                    // Convert scientific if toPrecision produced it, strip trailing zeros
                    let dec = num.toString();
                    if (dec.includes("e")) dec = Number(best).toFixed(10).replace(/0+$/, "");
                    return sign + formatJavaMantissa(dec);
                  }
                  let [mant, expPart] = Number(best).toExponential().split("e");
                  mant = mant.replace(/(\\.\\d*?[1-9])0+$/, "$1").replace(/\\.0+$/, "");
                  return sign + formatJavaMantissa(mant) + "E" + parseInt(expPart, 10);
                }

                export function parseJavaDouble(s) {
                  if (typeof s !== "string") return [0.0, 0];
                  const t = s.trim();
                  if (t.length === 0) return [0.0, 0];
                  if (t === "NaN" || t === "+NaN" || t === "-NaN") return [NaN, 1];
                  if (t === "Infinity" || t === "+Infinity") return [Infinity, 1];
                  if (t === "-Infinity") return [-Infinity, 1];
                  if (!/^[+-]?(\\d+(\\.\\d*)?|\\.\\d+)([eE][+-]?\\d+)?[fFdD]?$/.test(t)) return [0.0, 0];
                  const clean = /[fFdD]$/.test(t) ? t.slice(0, -1) : t;
                  const v = Number(clean);
                  return [v, 1];
                }

                export function parseJavaFloat(s) {
                  const [v, ok] = parseJavaDouble(s);
                  return ok ? [Math.fround(v), 1] : [0.0, 0];
                }

                export function createBabbleImports(options = {}) {
                  const onStdout = options.onStdout ?? options.stdout ?? ((s) => {
                    if (typeof process !== "undefined" && process.stdout) process.stdout.write(s);
                    else console.log(s);
                  });
                  const onStderr = options.onStderr ?? options.stderr ?? ((s) => {
                    if (typeof process !== "undefined" && process.stderr) process.stderr.write(s);
                    else console.error(s);
                  });
                  const cliArgs = Array.isArray(options.args)
                    ? options.args.map(String)
                    : (typeof process !== "undefined" && Array.isArray(process.argv) ? process.argv.slice(2) : []);
                  const env = {
                    write_stdout: (s) => onStdout(String(s)),
                    write_stderr: (s) => onStderr(String(s)),
                    format_f64: (d) => formatJavaDouble(d),
                    format_f32: (f) => formatJavaFloat(f),
                    parse_f64: (s) => parseJavaDouble(s),
                    parse_f32: (s) => parseJavaFloat(s),
                    args_count: () => cliArgs.length,
                    arg_at: (i) => cliArgs[i] ?? "",
                    now_ms: () => BigInt(Date.now()),
                  };
                  const imports = { "babble:env": env };
                  const extra = options.imports ?? options.host;
                  if (extra && typeof extra === "object") {
                    for (const [k, v] of Object.entries(extra)) {
                      imports[k] = v;
                    }
                  }
                  return imports;
                }

                export async function instantiateBabble(bytes, options = {}) {
                  const mod = await WebAssembly.compile(bytes, { builtins: ["js-string"] });
                  const imports = createBabbleImports(options);
                  return await WebAssembly.instantiate(mod, imports);
                }

                export async function runWasmBytes(bytes, options = {}) {
                  const instance = await instantiateBabble(bytes, options);
                  if (typeof instance.exports._babble_run === "function") {
                    const status = instance.exports._babble_run();
                    if (status !== 0) {
                      const err = typeof instance.exports._babble_error_js === "function"
                        ? instance.exports._babble_error_js()
                        : "Uncaught Babble exception";
                      const e = new Error(err);
                      e.babbleMessage = err;
                      throw e;
                    }
                    return typeof instance.exports._babble_result_js === "function"
                      ? instance.exports._babble_result_js()
                      : null;
                  }
                  if (typeof instance.exports._start === "function") {
                    instance.exports._start();
                  }
                  return null;
                }

                export async function runBabble(options = {}) {
                  let bytes;
                  if (typeof process !== "undefined" && process.versions?.node) {
                    const fs = await import("node:fs/promises");
                    const url = new URL(WASM_FILE, import.meta.url);
                    bytes = await fs.readFile(url);
                  } else {
                    const url = new URL(WASM_FILE, import.meta.url);
                    const resp = await fetch(url);
                    bytes = new Uint8Array(await resp.arrayBuffer());
                  }
                  const instance = await instantiateBabble(bytes, options);
                  if (options.runStart !== false && typeof instance.exports._start === "function") {
                    instance.exports._start();
                  }
                  return instance;
                }

                // Auto-run when invoked directly as a Node.js script: `node app.mjs`
                if (typeof process !== "undefined" && process.argv?.[1]) {
                  const path = await import("node:path");
                  const url = await import("node:url");
                  const selfPath = path.resolve(url.fileURLToPath(import.meta.url));
                  const entryPath = path.resolve(process.argv[1]);
                  if (selfPath === entryPath) {
                    const instance = await runBabble({ runStart: false });
                    if (typeof instance.exports._babble_run === "function") {
                      const status = instance.exports._babble_run();
                      if (status !== 0) {
                        const err = typeof instance.exports._babble_error_js === "function"
                          ? instance.exports._babble_error_js()
                          : "Uncaught Babble exception";
                        process.stderr.write("Error : " + err + "\\n");
                        process.exitCode = 1;
                      }
                    } else if (typeof instance.exports._start === "function") {
                      instance.exports._start();
                    }
                  }
                }
                """.formatted(escapedName);
    }
}
